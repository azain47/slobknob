/** Icon for a custom slice without its own icon, by slice kind. */
const KIND_ICONS = { action: "zap", wheel: "layers" };

const FALLBACK = "circle";

/** Every icon name, for the settings icon picker (mode icons first). */
export const ICON_NAMES = [...new Set([...Object.values(MODE_ICONS), ...Object.keys(SHAPES)])].filter(
  (n) => n !== FALLBACK,
);

/**
 * Icon name for a slice: its own `icon` if known, else the mode's icon, else
 * a default for its kind, else a plain circle. Never returns an unknown name.
 */
export function resolveIcon(id, icon, kind) {
  if (icon && SHAPES[icon]) return icon;
  const m = MODE_ICONS[id];
  if (m) return m;
  const k = KIND_ICONS[kind];
  return k || FALLBACK;
}

/** Inner SVG markup (24x24 coordinate space) for a slice (or plain mode id). */
export function iconShapes(id, icon, kind) {
  return SHAPES[resolveIcon(id, icon, kind)] ?? SHAPES[FALLBACK];
}

/** Inner SVG markup for an icon name, falling back to the default icon. */
export function namedIconShapes(name) {
  return SHAPES[name] ?? UI_SHAPES[name] ?? SHAPES[FALLBACK];
}

/**
 * Attributes + inner markup for a nested <svg> icon. Strokes use currentColor.
 * x/y/size are in the parent's user units; the icon is centered on (cx, cy).
 * `icon` / `kind` are optional (see resolveIcon).
 */
export function iconSvg(id, cx, cy, size, strokeWidth = 2, cls = "", icon = null, kind = null) {
  const h = size / 2;
  return (
    `<svg class="${cls}" x="${cx - h}" y="${cy - h}" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` +
    iconShapes(id, icon, kind) +
    "</svg>"
  );
}
